class TestLoop(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self._old = os.environ.get("CHRONICLER_LOOP_DIR")
        os.environ["CHRONICLER_LOOP_DIR"] = self.tmp.name

    def tearDown(self):
        if self._old is None:
            os.environ.pop("CHRONICLER_LOOP_DIR", None)
        else:
            os.environ["CHRONICLER_LOOP_DIR"] = self._old

    def _finding(self, key="a"):
        return checks.Finding(
            rule="DOC-PATH-MISSING", severity="high", title=f"missing {key}",
            doc="README.md", detail="d", action="a", key=key,
        )

    def test_reconcile_add_resolve_reopen(self):
        state = loop.empty_state()
        first = loop.reconcile(state, [self._finding("a")], cycle=1, now="2026-11-01T00:00:00Z")
        self.assertEqual(first["new"], 1)
        self.assertEqual(len(state["items"]), 1)

        silent = loop.reconcile(state, [], cycle=2, now="2026-11-02T00:00:00Z")
        self.assertEqual(silent["resolved"], 1)
        self.assertEqual(state["items"][0]["status"], "resolved")

        again = loop.reconcile(state, [self._finding("a")], cycle=3, now="2026-11-03T00:00:00Z")
        self.assertEqual(again["reopened"], 1)
        self.assertEqual(state["items"][0]["status"], "open")

    def test_close_is_recorded_and_persisted(self):
        state = loop.empty_state()
        loop.reconcile(state, [self._finding("a")], cycle=1, now="2026-11-01T00:00:00Z")
        loop.save_state(state)
        item_id = state["items"][0]["id"]

        closed = loop.close_item(item_id, note="fixed and verified")
        self.assertEqual(closed["status"], "done")
        reloaded = loop.load_state()
        self.assertEqual(reloaded["items"][0]["status"], "done")
        self.assertIn("fixed and verified", loop.journal_path().read_text())

    def test_priority_prefers_severe_and_instruction_docs(self):
        now = util.utcnow()
        state = loop.empty_state()
        loop.reconcile(state, [
            checks.Finding(rule="DOC-BARE-REF", severity="low", title="low", doc="README.md", detail="", action=""),
            checks.Finding(rule="DOC-PATH-MISSING", severity="high", title="high", doc="OPERATING_MANUAL.md", detail="", action=""),
        ], cycle=1, now=util.iso(now))
        snapshot = _snapshot(documents=[
            _doc(path="README.md", doc_class="introduction"),
            _doc(path="OPERATING_MANUAL.md", doc_class="instruction"),
        ])
        queue = loop.candidates(state, snapshot, now_dt=now)
        self.assertEqual(queue[0]["severity"], "high")
        self.assertEqual(queue[0]["doc"], "OPERATING_MANUAL.md")

    def test_empty_queue_picks_a_sweep(self):
        now = util.utcnow()
        state = loop.empty_state()
        snapshot = _snapshot(documents=[_doc(path="README.md"), _doc(path="OPERATING_MANUAL.md")])
        item = loop.ensure_sweep(state, snapshot, cycle=1, now=util.iso(now))
        self.assertIsNotNone(item)
        self.assertEqual(item["rule"], "SWEEP")

    def test_next_markdown_contains_the_work_order(self):
        state = loop.empty_state()
        loop.reconcile(state, [self._finding("a")], cycle=1, now="2026-11-01T00:00:00Z")
        snapshot = _snapshot(documents=[_doc()])
        rendered = loop.render_next(state, snapshot, state["items"][0])
        self.assertIn("Do this now", rendered)
        self.assertIn(state["items"][0]["id"], rendered)
        self.assertIn("python -m chronicler close", rendered)

    def test_shrinking_finding_keeps_the_deferred_item(self):
        state = loop.empty_state()
        now = "2026-11-01T00:00:00Z"
        first = self._finding("a")
        loop.reconcile(state, [first], cycle=1, now=now)
        item_id = state["items"][0]["id"]
        loop.save_state(state)
        loop.defer_item(item_id, reason="waiting on the owner")
        state.update(loop.load_state())

        changed = checks.Finding(
            rule="DOC-PATH-MISSING", severity="high", title="fewer missing", doc="README.md",
            detail="d", action="a", key="b",
        )
        stats = loop.reconcile(state, [changed], cycle=2, now="2026-11-02T00:00:00Z")

        self.assertEqual(len(state["items"]), 1)
        self.assertEqual(state["items"][0]["id"], item_id)
        self.assertEqual(state["items"][0]["status"], "deferred")
        self.assertEqual(state["items"][0]["finding_key"], "b")
        self.assertEqual(stats["new"], 0)
        self.assertEqual(stats["resolved"], 0)

    def test_deferred_without_a_date_is_parked(self):
        now = util.parse_date("2026-11-08T00:00:00Z")
        base = {"id": "a", "status": "deferred", "severity": "high"}
        self.assertFalse(loop._eligible(dict(base), now))
        self.assertFalse(loop._eligible(dict(base, defer_until="2026-12-01"), now))
        self.assertTrue(loop._eligible(dict(base, defer_until="2026-11-01"), now))
        self.assertTrue(loop._eligible({"id": "b", "status": "open", "severity": "high"}, now))


