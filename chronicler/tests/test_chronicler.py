class TestClassifyToken(unittest.TestCase):
    def test_accepts_repo_paths(self):
        cases = {
            "registry/claims.csv": ("relative", "registry/claims.csv"),
            "runs/5a9f093a2fe0/manifest.json": ("relative", "runs/5a9f093a2fe0/manifest.json"),
            "AI Agent Audits/evidence/verify_manifest.py": (
                "relative",
                "AI Agent Audits/evidence/verify_manifest.py",
            ),
            "test_output/": ("relative", "test_output"),
            "AIEF_1_4_FORWARD_PLAN.md": ("bare", "AIEF_1_4_FORWARD_PLAN.md"),
        }
        for raw, expected in cases.items():
            with self.subTest(raw=raw):
                self.assertEqual(docs.classify_token(raw), expected)

    def test_rejects_non_paths(self):
        rejects = [
            "python audits/engineering/verify_inventory.py",   # a command
            "pytest tools/ci/tests -q",                        # a command
            "lambda_B/alpha_EMA",                              # a ratio
            "B_carrier_only/full_reset",                       # a mode label
            "EMP-AIEF13-01/02",                                # a label pair
            "arena/d4a487cc-aiefs",                            # a branch
            "integration/round5",                              # a branch
            "38/40",                                           # a score
            "s_i = min(1, c/(q_i+ε",                           # a formula
            "κ_k = kη/c − 1/T_w",                              # a formula
            ".zip",                                            # an extension
            "FILE.md",                                         # a placeholder
            "lean/AIEFProofs/.lake",                           # generated by the build
            "https://example.com/x.md",                        # a URL
        ]
        for raw in rejects:
            with self.subTest(raw=raw):
                self.assertIsNone(docs.classify_token(raw))


