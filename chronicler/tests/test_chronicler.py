def _snapshot(**overrides) -> dict:
    base = {
        "schema": 1,
        "ref": "origin/main",
        "ref_commit": {"sha": "a" * 40, "date": "2026-11-01T00:00:00Z", "subject": "x"},
        "history": {"shallow": False, "commits": 500, "reliable": True},
        "remote": {"ok": False, "error": "offline", "heads": {}},
        "counts": {"tracked_files": 100},
        "pins": [],
        "pin_summary": {"total": 0, "present": 0, "matching": 0, "mismatched": [], "missing": []},
        "errata_covered": [],
        "universe": ["registry/claims.csv", "README.md", "docs/deep/file.md"],
        "documents": [],
        "manifest": {"stale_after_days": 14},
    }
    base.update(overrides)
    return base


def _doc(doc_class: str | None = None, **overrides) -> dict:
    base = {
        "path": "README.md",
        "ref": "origin/main",
        "class": "introduction",
        "editable": True,
        "required": True,
        "required_sections": [],
        "max_age_days": 30,
        "watch": [],
        "check_counts": False,
        "present": True,
        "declared_date": "2026-11-01",
        "declared_date_line": 3,
        "age_days": 1.0,
        "headings": [],
        "cited_shas": [],
        "cited_paths": [],
        "stated_counts": [],
        "branch_rows": [],
        "commit": {"sha": "b" * 40, "date": "2026-11-01T00:00:00Z"},
        "watch_newest": None,
        "is_pinned": False,
        "pinned_by": [],
        "ref_candidates": ["origin/main"],
    }
    if doc_class is not None:
        base["class"] = doc_class
    base.update(overrides)
    return base


