#!/usr/bin/env python3
"""Decompose the delayed phase balance that stabilizes the K3 source difference.

For a directed edge e=(i,j), the implemented source phase is

    phi_e = theta_i - history_oldest_j - ((omega_i+omega_j)/2) tau,
    z_e   = exp(i phi_e).

The constant frequency correction drops out of the temporal increment.  The
exact modulo-2pi source-phase increment is generated by

    dphi_e = dt (omega_i + coupling_i) - dhistory_j.

For the forward and reverse comparisons of edges 25 and 59, this script
separates mean-phase and phase-separation increments into intrinsic-frequency,
current-coupling, and delayed-history contributions.  It checks the exact
complex source increment, first-order source increment, mean/separation
linearization, cancellation of large phase terms, and convergence of the mean
and separation to fixed late values.
"""

