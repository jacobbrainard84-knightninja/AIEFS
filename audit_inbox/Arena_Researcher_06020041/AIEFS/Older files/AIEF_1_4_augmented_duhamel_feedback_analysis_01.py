def file_sha256(path: str | os.PathLike[str]) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def parse_nonnegative_float_list(value: str) -> list[float]:
    try:
        values = [float(item.strip()) for item in value.split(",") if item.strip()]
    except ValueError as exc:
        raise argparse.ArgumentTypeError("expected comma-separated floats") from exc
    if not values or any(item < 0.0 for item in values):
        raise argparse.ArgumentTypeError("values must be nonnegative")
    return sorted(set(values))


def json_compact(value: Any) -> str:
    return json.dumps(value, separators=(",", ":"), sort_keys=True)


def centered_B(
    plus: augmented.TangentState,
    minus: augmented.TangentState,
    edges: tuple[np.ndarray, np.ndarray],
    selected_edges: np.ndarray,
) -> np.ndarray:
    return 0.5 * (plus.B[edges][selected_edges] - minus.B[edges][selected_edges])


def cosine(left: np.ndarray, right: np.ndarray) -> float:
    denominator = np.linalg.norm(left) * np.linalg.norm(right)
    if denominator <= ZERO_TOL:
        return np.nan
    return float(left @ right / denominator)


def bin_index(time_value: float, boundaries: np.ndarray) -> int:
    index = int(np.searchsorted(boundaries, time_value, side="right") - 1)
    return min(max(index, 0), len(boundaries) - 2)


def initialize_tangent_pair(
    split_state: base.DynamicState,
    full_direction: np.ndarray,
    node_count: int,
    edges: tuple[np.ndarray, np.ndarray],
) -> tuple[augmented.TangentState, augmented.TangentState]:
    plus = augmented.zero_tangent_like(split_state)
    minus = augmented.zero_tangent_like(split_state)
    plus.B = base.vector_to_matrix(full_direction, node_count, edges)
    minus.B = -plus.B.copy()
    return plus, minus


def make_report(
    trajectory: pd.DataFrame,
    bin_frame: pd.DataFrame,
    ablation_summary: pd.DataFrame,
    forcing_final: pd.DataFrame,
    *,
    seed: str,
    final_replay_exact: bool,
    final_replay_max_error: float,
) -> str:
    lines = [
        "AIEF exceptional K3 augmented Duhamel feedback analysis",
        "========================================================",
        "",
        "Identity and decomposition",
        "--------------------------",
        f"Seed: {seed}",
        f"Final base replay exact: {final_replay_exact}",
        f"Final base replay maximum error: {final_replay_max_error:.6g}",
        "* The weight-block forcing is endogenous to the closed augmented tangent system.",
        "",
        "Direction-wise Duhamel results",
        "--------------------------------",
    ]
    for direction_id, group in trajectory.groupby("direction_id"):
        finite_ratio = group.loc[np.isfinite(group["feedback_to_homogeneous_ratio"])]
        crossed = finite_ratio.loc[
            finite_ratio["feedback_to_homogeneous_ratio"] >= 1.0
        ]
        crossing_time = float(crossed.iloc[0]["time"]) if len(crossed) else np.nan
        final = group.iloc[-1]
        lines.append(
            f"  direction={int(direction_id)}: crossover_time={crossing_time:.6g}, "
            f"final_h_norm={final['homogeneous_norm']:.6g}, "
            f"final_feedback_norm={final['feedback_norm']:.6g}, "
            f"final_total_norm={final['total_norm']:.6g}, "
            f"final_ratio={final['feedback_to_homogeneous_ratio']:.6g}, "
            f"max_reconstruction_error={group['duhamel_reconstruction_relative_error'].max():.3g}, "
            f"median_instant_forcing_ratio={group['instant_forcing_to_homogeneous_output_ratio'].median():.3g}, "
            f"median_principal_output_alignment={group['forcing_principal_output_alignment'].median():.3g}, "
            f"median_driver_match_error={group['driver_forcing_relative_error'].median():.3g}"
        )

    lines.extend(["", "Forcing-time attribution at final horizon", "-----------------------------------------"])
    for direction_id, group in forcing_final.groupby("direction_id"):
        strongest = group.loc[group["propagated_contribution_norm"].idxmax()]
        lines.append(
            f"  direction={int(direction_id)}: strongest forcing step={int(strongest['forcing_step'])}, "
            f"time={strongest['forcing_time']:.6g}, "
            f"propagated_norm={strongest['propagated_contribution_norm']:.6g}, "
            f"future_input_alignment={strongest['alignment_with_principal_future_input']:.6g}, "
            f"alignment_with_final_feedback={strongest['alignment_with_final_feedback']:.6g}"
        )

    lines.extend(["", "Time-bin attribution", "--------------------"])
    final_targets = bin_frame.loc[
        bin_frame["target_time"] == bin_frame["target_time"].max()
    ]
    for direction_id, group in final_targets.groupby("direction_id"):
        lines.append(f"  direction={int(direction_id)}:")
        for _, row in group.iterrows():
            lines.append(
                f"    [{row['bin_start']:.6g},{row['bin_end']:.6g}): "
                f"norm={row['contribution_norm']:.6g}, "
                f"alignment={row['alignment_with_total_feedback']:.6g}"
            )

    lines.extend(["", "Counterfactual tangent ablations", "--------------------------------"])
    for _, row in ablation_summary.iterrows():
        lines.append(
            f"  direction={int(row['direction_id'])}, ablation={row['ablation']}: "
            f"resolved={int(row['resolved_sample_count'])}, "
            f"last_time={row['last_resolved_time']:.6g}, "
            f"median_relative_difference={row['median_relative_difference']:.6g}, "
            f"maximum={row['maximum_relative_difference']:.6g}, "
            f"last_norm_ratio={row['final_norm_ratio']:.6g}, "
            f"last_alignment={row['final_alignment']:.6g}"
        )

    lines.extend(
        [
            "",
            "Interpretation constraints",
            "--------------------------",
            "* Duhamel forcing is a weight-block representation of an internally generated closed-system feedback.",
            "* The residual forcing b[n+1]-K[n]b[n] gives an exact direction-wise decomposition.",
            "* Direct projected dR forcing is compared with that residual; equality relies on linear restriction/additivity.",
            "* Time-bin vectors can cancel, so their norms are not additive percentages.",
            "* Ablations alter recursive tangent feedback and are controlled counterfactuals, not additive causal fractions.",
            "* Results remain conditional on this seed, branch, and tested initial directions.",
            "",
        ]
    )
    return "\n".join(lines)


