#!/usr/bin/env python3
"""Duhamel and block-feedback analysis of the validated augmented AIEF tangent.

For each saved exceptional-K3 initial direction, this script propagates the
validated augmented +h and -h directional tangents along the exact base replay.
It then decomposes the centered K3 weight tangent exactly as

    b_n = h_n + r_n,
    h_{n+1} = K_n h_n,
    r_{n+1} = K_n r_n + f_n,
    f_n = b_{n+1} - K_n b_n.

Here K_n is the already validated frozen-driver weight block.  The forcing
f_n is endogenous: it is generated by the phase/history/EMA tangent variables
of the closed augmented system.  The script compares f_n with the directly
computed projected dR-to-weight contribution, finds feedback crossover times,
measures cancellation angles, attributes final/target feedback to time bins,
and propagates selected counterfactual tangent ablations along the unchanged
base trajectory.

Ablations are mechanistic counterfactuals, not additive causal percentages:
* no_current_phase in the EMA phase difference;
* no_delayed_history in the EMA phase difference;
* no_ema_memory;
* no_fresh_phase forcing into EMA;
* no_R_to_weight feedback.
"""

