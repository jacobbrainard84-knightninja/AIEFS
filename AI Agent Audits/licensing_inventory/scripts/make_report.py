#!/usr/bin/env python3
"""Build INVENTORY.md from inventory.json. Prints no PII values (inventory.json holds none)."""
import json, collections, sys, os
here = os.path.dirname(os.path.abspath(__file__)); base = os.path.dirname(here)
d = json.load(open(os.path.join(base, "inventory.json")))

# Post-filter known false positives (also fixed in inventory.py for future runs).
d["pii_findings"] = [p for p in d["pii_findings"] if not (p["path"] == "tools/sync/upload_new.sh" and p["type"] == "email")]
# Sanitise: trim URL junk glued onto scraped DOIs (one contained a private IP), and use the repo name, not a local path.
import re as _re
for _f in d["files"]:
    _e = _f.get("evidence") or {}
    if "dois" in _e:
        _e["dois"] = sorted({_re.split(r"https?://", x)[0] for x in _e["dois"]} - {""})
d["repo"] = "jacobbrainard84-knightninja/AIEFS"
json.dump(d, open(os.path.join(base, "inventory.json"), "w"), indent=1, ensure_ascii=False)

files = d["files"]; by = collections.defaultdict(list)
for f in files: by[f["category"]].append(f)
def mb(n): return f"{n/1e6:.1f} MB"
def pages(f): return (f.get("pdfinfo") or {}).get("Pages", "")

CAT2 = {
 "Project Origins/SSRH 001 stuff.pdf": ("Grok-style research chat ('Thought for Ns', 63 'Deep Dive' sections)",
   "Full or near-full text of several pasted papers, e.g. an AAS 2005 paper (p.24), a Phys. Rev. Lett. 2019 APS paper (p.53), "
   "Science Advances 2025 Aguilar & Lutz (pp.~497-512), Nature Astronomy 2019 Gurnett & Kurth, npj 2D Materials 2025, "
   "J. Power Sources 2026 (Tran & Le-Quoc), a ResearchGate piezoelectric water-ice paper; plus reference lists and abstracts.",
   "Substantial: ~108 of 933 pages show journal-style text (heuristic); several whole papers."),
 "Project Histories/SSRH 000244 Stuff.odt": ("Grok-style research chat (203 'Thought for' markers)",
   "Pasted papers/abstracts incl. an AIMS Press 2025 paper (CC BY), Jian Ma et al. 2012 (open access), a 2024 CC BY article, "
   "a Springer 2020 paper, author affiliation blocks; 139 DOIs cited.",
   "Substantial: ~54 sixty-line blocks flagged (heuristic) out of ~25k text lines."),
 "Project Origins/SSH history part 002461.pdf": ("Grok conversation 'Help me Write My SSrH Paper' (You/Grok turns)",
   "Pasted excerpts of papers incl. a 2025 article (p.108 copyright line) and a 2024 CC BY article (p.453); "
   "affiliation blocks and abstracts (e.g. pp.106-113, 122-139).",
   "Moderate: ~45 of 763 pages flagged (heuristic)."),
 "Project Origins/grok ice 4009942.pdf": ("'User Statement / AI Agent Response' chat",
   "Pasted PNAS article Dalal et al. 2015 (doi 10.1073/pnas.1421042112) with publisher download watermarks (pp.~17-35), "
   "plus other pasted excerpts (e.g. p.55).",
   "Moderate: ~20 of 80 pages flagged; one near-complete article."),
 "Project Origins/grok ice 400994202.pdf": ("'User Statement: Examine the attached documents' chat",
   "AI summary of an attached delay-differential-equation thesis; the thesis itself is NOT in the repo.",
   "Minimal: paraphrase/summary only (5 pages)."),
 "Project Origins/SSRH stuff.pdf": ("AI chat export ('Statement:' turns + AI 'deep dive' replies); also the attachment that opens 'SSH history part 002461.pdf'",
   "AI-written summaries of third-party papers (e.g. Yoon et al. 2025, Li et al. 2024) and bibliographic URL lists (p.12).",
   "Minimal: no full-text pastes found; ~6 of 221 pages are reference lists."),
 "Project Histories/Project Lead History 03.pdf": ("AIEF project chat (Project Lead History 03)",
   "AI discussion of Martens & Bick (adaptive networks, ~pp.1510-1532), Berner et al. 'Adaptive Dynamical Networks' (~pp.1518-1532), "
   "and the Ohira cross-feedback DDE paper (pp.20, 1151-1152, 1262).",
   "Minimal: paraphrase and short quoted phrases; no pasted paper pages detected."),
}

L = []; w = L.append
w("# AIEF repository: licence and content inventory\n")
w(f"Repository: `{d['repo']}` at commit `{d['head'][:7]}`. Total files scanned: **{d['file_count']}** "
  "(all git-tracked files; zip archives scanned inside).\n")
w("Generated by `scripts/inventory.py` (scan) and `scripts/make_report.py` (this report). "
  "**Nothing was changed in the GitHub repo.** Personal details are described by type and location only, never copied.\n")
c = collections.Counter(f["category"] for f in files)
w("## Summary\n\n| Category | Meaning | Files |\n|---|---|---|")
w(f"| 1 | Standalone third-party papers (owner decided: delete) | {c['1']} |")
w(f"| 2 | Third-party material inside AI conversations (keep) | {c['2']} |")
w(f"| UNSURE | Needs owner decision | {sum(1 for f in files if f.get('unsure'))+1} (listed below; also counted in their main category) |")
npii = len({p['path'] for p in d['pii_findings']})
w(f"| 3 | Files containing personal information | {npii} files ({len(d['pii_findings'])} findings), overlaps other categories |")
w(f"| 4 | Own work | {c['4']} |\n")

w("## Category 1: standalone third-party papers (delete candidates)\n")
w("| Path | Size | Title | Authors | Source / DOI | Evidence | Does deleting break a reference? |\n|---|---|---|---|---|---|---|")
SRC = {"Papers/2804.05652v1.pdf": "arXiv:2304.05652v1 [nlin.AO], 12 Apr 2023 (later Physics Reports). arXiv non-exclusive distribution licence. Filename typo: 2804 for 2304.",}
TITLE = {"Papers/2804.05652v1.pdf": ("Adaptive Dynamical Networks", "Rico Berner, Thilo Gross, Christian Kuehn, Jürgen Kurths, Serhiy Yanchuk"),
 "Papers/The Holland Atom_Paper_1_30.May.2026_v1.pdf": ("The Holland Atom, Paper 1 (30 May 2026, v1)", "John Edward Holland"),
 "Papers/The Holland Atom_Paper 2 Radius Variation 23.Jun.2026_v1.0.pdf": ("The Holland Atom, Paper 2: Radius Variation (23 Jun 2026, v1.0)", "John Edward Holland"),
 "Papers/H-Atom_Paper 3 Geometric Radius Scaling Law 19.Jul.2026_v1.0.pdf": ("H-Atom Paper 3: Geometric Radius Scaling Law (19 Jul 2026, v1.0)", "John Edward Holland")}
for f in sorted(by["1"], key=lambda x: x["path"]):
    t, a = TITLE.get(f["path"], ((f.get("pdfinfo") or {}).get("Title", ""), (f.get("pdfinfo") or {}).get("Author", "")))
    src = SRC.get(f["path"], "Self-published by the author (no DOI); page 1: '© Copyright. John Holland 2026. All rights reserved.'")
    refs = "; ".join(f"{r['path']} ({r.get('unit') or 'line '+str(r.get('line'))})" for r in f.get("references", []))
    ev = f"{pages(f)} pages; " + f["reason"].split(" ALSO FLAGGED")[0]
    w(f"| `{f['path']}` | {mb(f['size'])} | {t} | {a} | {src} | {ev} | No functional break. Filename only mentioned in: {refs}. No code loads it. |")
w("")
w("## Category 2: third-party material inside AI conversations (keep, fair-use context)\n")
w("| Path | Conversation | What is quoted | Roughly how much |\n|---|---|---|---|")
for f in sorted(by["2"], key=lambda x: x["path"]):
    conv, what, amt = CAT2.get(f["path"], ("", f["reason"], ""))
    w(f"| `{f['path']}` ({mb(f['size'])}{', '+pages(f)+' pp.' if pages(f) else ''}) | {conv} | {what} | {amt} |")
w("\nNote: 'flagged' pages come from a heuristic (publisher copyright lines, DOI/affiliation blocks, journal hyphenation, "
  "numbered reference lists). It is an estimate, not an exact count. Other PDFs that merely sit next to chats were not counted.\n")

w("## UNSURE: owner decision needed\n")
w("| Path | Current category | Why unsure |\n|---|---|---|")
for f in files:
    if f.get("unsure"): w(f"| `{f['path']}` | {f['category']} | {f['unsure']} |")
w("| `Project Origins/SSRH stuff.pdf` | 2 | Either a conversation export (category 2) or the owner's compiled working draft (category 4). Both mean KEEP, so no action depends on it. |")
w("")

w("## Category 3: personal information (types and locations only, no values)\n")
w("### Not fixable without rewriting history\n")
ge = d["git_history_commit_emails"]
w(f"- **Owner's personal Gmail address is in the git commit metadata** (author/committer) of {ge.get('personal webmail (gmail)',0)} of "
  f"{sum(ge.values())} commits; the other {ge.get('github noreply',0)} use a GitHub no-reply address. It is public on GitHub and "
  "cannot be removed without rewriting history (not done). For future commits, set `git config user.email` to the GitHub no-reply address.\n")
w("### In files\n")
w("| Path | PII type | Whose / kind | Location (page:line of extracted text, or line) |\n|---|---|---|---|")
g = collections.defaultdict(list)
for p in d["pii_findings"]:
    if p["type"] == "home-directory path": continue
    g[(p["path"], p["type"], p["class"])].append(f"{p['unit'].replace('page ','p.').replace('text','line').replace('doc','line')}:{p['line']}" if p['unit'] not in ('text','doc') else f"line {p['line']}")
for (path, typ, cls), locs in sorted(g.items()):
    w(f"| `{path}` | {typ} | {cls} | {', '.join(locs)} |")
home = [p for p in d["pii_findings"] if p["type"] == "home-directory path"]
hp = collections.Counter(p["path"] for p in home)
w(f"\n**Home-directory paths:** {len(home)} occurrences in {len(hp)} files (e.g. `/home/<user>/...`, `/Users/<user>/...`) "
  "with non-identifying usernames (not the owner's name): low risk, they reveal machine layout but not identity. Files with the most hits:\n")
for path, n in hp.most_common(15): w(f"- `{path}`: {n}")
w(f"- ...and {max(0,len(hp)-15)} more files (see `inventory.json`, field `pii_findings`).\n")
w("**Other notes**\n")
w("- The IPv4 addresses in `Project Origins/grok ice 4009942.pdf` are publisher download watermarks (the IP of whoever downloaded the PNAS article; likely the owner's).")
w("- Third-party author emails/ORCIDs/postal addresses are part of the pasted papers' author blocks. The two personal webmail addresses (third-party authors) are in `Project Origins/SSRH 001 stuff.pdf`.")
w("- `aief_modular/artifacts.py` (in `AIEF_Experiments/aief_modular_platform_v1_analysis_v4/` line 315, and in the `workspace-019ff86e…` copy line 225) records the computer's hostname into run manifests; consider removing for future runs.")
w("- No passwords, API keys or tokens were found. The owner's real name does not appear in content; the GitHub username appears in repo URLs.\n")

w("## Existing licence / copyright headers\n")
w("| Path | Location | Text |\n|---|---|---|")
for h in d["license_headers"]:
    loc = f"line {h['line']}" if h['unit'] in ('text','doc') else f"{h['unit'].replace('page ','p.')}, line {h['line']}"
    note = " (audit note quoting the Holland papers, not a header)" if h['path'].endswith('AIEFS_audit.md') else ""
    w(f"| `{h['path']}` | {loc} | {h['match'].replace('|','/')}{note} |")
w("""
**Conflicts and issues**

1. The two live Lean files (`lean/AIEFProofs/AIEFProofs/ControllerFiber.lean` and `ControllerFiberProjector.lean`, lines 2-3) say
   "Copyright (c) 2026 AIEF Proofs. All rights reserved." and then "Released under Apache 2.0 license as described in the file LICENSE."
   - "All rights reserved" next to an open licence looks contradictory. It is common Mathlib-style wording and harmless legally, but cleaner to drop.
   - The holder name "AIEF Proofs" differs from the new notice "Jacob Brainard and AIEF contributors".
   - They refer to a LICENSE file that does not exist yet (fixed once `LICENSE` is added at the repo root).
   - Suggested replacement: `Copyright 2026 Jacob Brainard and AIEF contributors` + `SPDX-License-Identifier: Apache-2.0`.
2. The four copies under `AI Agent Audits/lean_recovery/` carry the same header (same issues).
3. `Project Lead History 10.pdf` contains draft headers in conversation text ("AIEF / SSRH formalization", pp.299/305/324). They are not live files, so no action is needed.
4. The three Holland papers say "All rights reserved": that conflicts with publishing them in an openly-licensed repo (they are category-1 delete candidates).
5. The pasted third-party papers carry their own publisher notices (APS, AAAS, AIMS Press, CC BY). Those stay with their owners (see LICENSING.md section 3-4).
6. No SPDX identifiers exist anywhere. Mathlib is fetched as a Lean dependency (Apache-2.0), not vendored.
""")
w("## Category 4: own work (summary)\n")
own = by["4"]; ext = collections.Counter((f["ext"] or "(none)") for f in own)
top = collections.Counter(f["path"].split("/")[0] if "/" in f["path"] else "(repo root)" for f in own)
w(f"{len(own)} files, {mb(sum(f['size'] for f in own))} in total.\n\nBy file type: " + ", ".join(f"{k} {v}" for k, v in ext.most_common(15)) + ".\n")
w("By top-level folder: " + ", ".join(f"`{k}` {v}" for k, v in top.most_common(20)) + (", ..." if len(top) > 20 else "") + ".\n")
w("Includes the AIEF code, Lean proofs, experiment outputs, the `Project Lead History 01-10` AI-chat transcripts, "
  "own Solar System Resonance Hypothesis drafts, and the zip archives of own code and reports.\n")
open(os.path.join(base, "INVENTORY.md"), "w").write("\n".join(L))
print("wrote INVENTORY.md", len(L), "lines")
